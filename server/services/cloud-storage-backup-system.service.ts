  /**
   * Perform automatic backup
   */
  static async performAutoBackup(userId: string): Promise<BackupJob> {
    console.log(`💾 Starting auto-backup for user ${userId}...`);

    const job: BackupJob = {
      jobId: crypto.randomUUID(),
      userId,
      type: 'auto',
      status: 'running',
      filesBackedUp: 0,
      totalSize: 0,
      startedAt: new Date(),
    };

    try {
      // Get all files modified since last backup
      const modifiedFiles = await this.getModifiedFilesSinceLastBackup(userId);

      for (const file of modifiedFiles) {
        // Create backup version
        await this.createBackupVersion(file);
        job.filesBackedUp++;
        job.totalSize += file.fileSize;
      }

      job.status = 'completed';
      job.completedAt = new Date();

      console.log(`✅ Auto-backup completed: ${job.filesBackedUp} files backed up`);

    } catch (error: any) {
      job.status = 'failed';
      job.error = error.message;
      console.error('❌ Auto-backup failed:', error);
    }

    await this.saveBackupJob(job);

    return job;
  }

