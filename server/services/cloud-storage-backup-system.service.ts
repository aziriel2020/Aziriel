  /**
   * Sync files across devices
   */
  static async syncDevice(
    userId: string,
    deviceId: string,
    deviceName: string
  ): Promise<SyncStatus> {
    console.log(`🔄 Syncing device: ${deviceName}`);

    const status: SyncStatus = {
      deviceId,
      deviceName,
      lastSyncAt: new Date(),
      filesInSync: 0,
      pendingChanges: 0,
      syncStatus: 'syncing',
    };

    try {
      // Get all user files
      const allFiles = await this.getUserFiles(userId);

      // Get device sync state
      const deviceState = await this.getDeviceSyncState(deviceId);

      // Calculate delta
      const filesToSync = allFiles.filter(f =>
        !deviceState.syncedFiles.includes(f.fileId) ||
        f.lastModified > deviceState.lastSyncAt
      );

      // Sync files
      for (const file of filesToSync) {
        await this.syncFileToDevice(deviceId, file);
        status.filesInSync++;
      }

      status.syncStatus = 'synced';
      status.pendingChanges = 0;

      console.log(`✅ Device synced: ${status.filesInSync} files`);

    } catch (error) {
      status.syncStatus = 'error';
      console.error('Sync error:', error);
    }

    await this.updateDeviceSyncState(deviceId, status);

    return status;
  }

