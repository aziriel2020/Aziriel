  /**
   * Upload file to cloud storage
   */
  static async uploadFile(
    userId: string,
    file: {
      fileName: string;
      fileSize: number;
      mimeType: string;
      data: Buffer | string; // Buffer for server, string (path) for client
    },
    options?: {
      projectId?: string;
      folderId?: string;
      versionComment?: string;
      accessLevel?: 'private' | 'team' | 'public';
    }
  ): Promise<CloudFile> {
    console.log(`☁️ Uploading file: ${file.fileName} (${this.formatBytes(file.fileSize)})`);

    // Step 1: Check storage quota
    const quota = await this.getStorageQuota(userId);
    if (quota.totalStorage !== -1 && quota.usedStorage + file.fileSize > quota.totalStorage) {
      throw new Error('Storage quota exceeded. Please upgrade your plan.');
    }

    // Step 2: Calculate checksum
    const checksum = this.calculateChecksum(file.data);

    // Step 3: Check for deduplication (same file already exists)
    const existingFile = await this.findDuplicateFile(userId, checksum);
    if (existingFile) {
      console.log('🔍 File already exists (deduplication). Linking instead of uploading.');
      return existingFile;
    }

    // Step 4: Upload to cloud storage (S3, GCS, or Azure Blob)
    const storagePath = await this.uploadToStorage(userId, file.fileName, file.data);

    // Step 5: Upload to CDN for fast global delivery
    const cdnUrl = await this.uploadToCDN(storagePath, file.mimeType);

    // Step 6: Create file record
    const cloudFile: CloudFile = {
      fileId: crypto.randomUUID(),
      userId,
      fileName: file.fileName,
      fileSize: file.fileSize,
      mimeType: file.mimeType,
      storagePath,
      cdnUrl,
      checksum,
      uploadedAt: new Date(),
      lastModified: new Date(),
      isDeleted: false,
      versions: [],
      sharedWith: [],
      accessLevel: options?.accessLevel || 'private',
      metadata: {
        projectId: options?.projectId,
        folderId: options?.folderId,
      },
    };

    // Step 7: Save to database
    await this.saveFileRecord(cloudFile);

    // Step 8: Create initial version
    await this.createFileVersion(cloudFile, userId, options?.versionComment);

    // Step 9: Trigger auto-backup
    this.triggerAutoBackup(userId);

    console.log(`✅ File uploaded successfully: ${cloudFile.cdnUrl}`);

    return cloudFile;
  }

  /**
   * Upload large file with chunked upload (resumable)
   */
  static async uploadLargeFile(
    userId: string,
    file: {
      fileName: string;
      fileSize: number;
      mimeType: string;
    }
  ): Promise<UploadSession> {
    console.log(`📦 Starting chunked upload for: ${file.fileName}`);

    const session: UploadSession = {
      sessionId: crypto.randomUUID(),
      userId,
      fileName: file.fileName,
      fileSize: file.fileSize,
      chunksTotal: Math.ceil(file.fileSize / this.CHUNK_SIZE),
      chunksUploaded: 0,
      uploadedBytes: 0,
      status: 'active',
      startedAt: new Date(),
      expiresAt: new Date(Date.now() + 7 * 24 * 60 * 60 * 1000), // 7 days
    };

    // Save session
    await this.saveUploadSession(session);

    return session;
  }

  /**
   * Upload chunk for resumable upload
   */
  static async uploadChunk(
    sessionId: string,
    chunkNumber: number,
    chunkData: Buffer
  ): Promise<{ progress: number; completed: boolean }> {
    // Get upload session
    const session = await this.getUploadSession(sessionId);
    if (!session) throw new Error('Upload session not found');

    // Upload chunk to storage
    await this.uploadChunkToStorage(sessionId, chunkNumber, chunkData);

    // Update session
    session.chunksUploaded++;
    session.uploadedBytes += chunkData.length;
    const progress = (session.chunksUploaded / session.chunksTotal) * 100;

    // Check if completed
    const completed = session.chunksUploaded === session.chunksTotal;
    if (completed) {
      session.status = 'completed';
      // Merge chunks and finalize upload
      await this.finalizeChunkedUpload(session);
    }

    await this.updateUploadSession(session);

    return { progress, completed };
  }

