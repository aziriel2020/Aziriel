  /**
   * Restore file to previous version
   */
  static async restoreFileVersion(
    fileId: string,
    versionId: string,
    userId: string
  ): Promise<CloudFile> {
    console.log(`⏮️ Restoring file to version ${versionId}...`);

    const file = await this.getFile(fileId, userId);
    if (!file) throw new Error('File not found');

    const version = file.versions.find(v => v.versionId === versionId);
    if (!version) throw new Error('Version not found');

    // Create new version from restored version
    const newVersion: FileVersion = {
      versionId: crypto.randomUUID(),
      versionNumber: file.versions.length + 1,
      fileSize: version.fileSize,
      storagePath: version.storagePath,
      cdnUrl: version.cdnUrl,
      checksum: version.checksum,
      createdAt: new Date(),
      createdBy: userId,
      comment: `Restored from version ${version.versionNumber}`,
      isActive: true,
    };

    // Set all other versions to inactive
    file.versions.forEach(v => v.isActive = false);

    // Add new version
    file.versions.push(newVersion);

    // Update file
    file.storagePath = newVersion.storagePath;
    file.cdnUrl = newVersion.cdnUrl;
    file.checksum = newVersion.checksum;
    file.lastModified = new Date();

    await this.updateFile(file);

    console.log(`✅ File restored to version ${version.versionNumber}`);

    return file;
  }

  /**
   * Create new file version
   */
  private static async createFileVersion(
    file: CloudFile,
    userId: string,
    comment?: string
  ): Promise<FileVersion> {
    const version: FileVersion = {
      versionId: crypto.randomUUID(),
      versionNumber: file.versions.length + 1,
      fileSize: file.fileSize,
      storagePath: file.storagePath,
      cdnUrl: file.cdnUrl,
      checksum: file.checksum,
      createdAt: new Date(),
      createdBy: userId,
      comment,
      isActive: true,
    };

    file.versions.push(version);
    await this.updateFile(file);

    return version;
  }

  /**
   * Compare two versions
   */
  static async compareVersions(
    fileId: string,
    versionId1: string,
    versionId2: string,
    userId: string
  ): Promise<{ differences: string[]; sizeDiff: number }> {
    const file = await this.getFile(fileId, userId);
    if (!file) throw new Error('File not found');

    const v1 = file.versions.find(v => v.versionId === versionId1);
    const v2 = file.versions.find(v => v.versionId === versionId2);

    if (!v1 || !v2) throw new Error('Version not found');

    return {
      differences: [`File size changed`, `Checksum different`],
      sizeDiff: v2.fileSize - v1.fileSize,
    };
  }

