  /**
   * Run deduplication scan
   */
  static async runDeduplicationScan(userId: string): Promise<{
    duplicatesFound: number;
    spaceSaved: number;
  }> {
    console.log('🔍 Running deduplication scan...');

    // Find all duplicate files by checksum
    const allFiles = await this.getUserFiles(userId);
    const checksumMap = new Map<string, CloudFile[]>();

    for (const file of allFiles) {
      if (!checksumMap.has(file.checksum)) {
        checksumMap.set(file.checksum, []);
      }
      checksumMap.get(file.checksum)!.push(file);
    }

    let duplicatesFound = 0;
    let spaceSaved = 0;

    for (const [checksum, files] of checksumMap) {
      if (files.length > 1) {
        // Keep first file, deduplicate others
        for (let i = 1; i < files.length; i++) {
          await this.deduplicateFile(files[i], files[0]);
          duplicatesFound++;
          spaceSaved += files[i].fileSize;
        }
      }
    }

    console.log(`✅ Deduplication complete: ${duplicatesFound} duplicates, ${this.formatBytes(spaceSaved)} saved`);

    return { duplicatesFound, spaceSaved };
  }

